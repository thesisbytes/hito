#!/usr/bin/env python3
"""Write the glyph list for the kana superset the vocab realm traces.

The hiragana pack is the 46 gojūon and nothing else, because the chart is the
point of it. A vocabulary deck is not so tidy: だいがく wants が, いっぷん wants
っ and ぷ, アメリカ wants katakana, and コンピューター wants ュ and ー. Rather
than grow the list every time a lesson introduces a character, this emits
every hiragana and katakana in one go — 164 glyphs — so a deck is only ever a
JSON edit. Stroke data for all of them comes from KanjiVG, same as the gojūon.

Usage:  kana_glyphs.py <out glyphs.json>
"""

import json
import sys
from pathlib import Path

# Row order follows the gojūon, then the voiced rows, then the small kana.
# Romaji is Hepburn, with the x- prefix for small kana the way an IME types
# them. ん is "n", which the stitch treats as belonging to no vowel column.
HIRAGANA = [
    ("a",   "あいうえお",      ["a", "i", "u", "e", "o"]),
    ("ka",  "かきくけこ",      ["ka", "ki", "ku", "ke", "ko"]),
    ("sa",  "さしすせそ",      ["sa", "shi", "su", "se", "so"]),
    ("ta",  "たちつてと",      ["ta", "chi", "tsu", "te", "to"]),
    ("na",  "なにぬねの",      ["na", "ni", "nu", "ne", "no"]),
    ("ha",  "はひふへほ",      ["ha", "hi", "fu", "he", "ho"]),
    ("ma",  "まみむめも",      ["ma", "mi", "mu", "me", "mo"]),
    ("ya",  "やゆよ",          ["ya", "yu", "yo"]),
    ("ra",  "らりるれろ",      ["ra", "ri", "ru", "re", "ro"]),
    ("wa",  "わを",            ["wa", "wo"]),
    ("n",   "ん",              ["n"]),
    ("ga",  "がぎぐげご",      ["ga", "gi", "gu", "ge", "go"]),
    ("za",  "ざじずぜぞ",      ["za", "ji", "zu", "ze", "zo"]),
    ("da",  "だぢづでど",      ["da", "ji", "zu", "de", "do"]),
    ("ba",  "ばびぶべぼ",      ["ba", "bi", "bu", "be", "bo"]),
    ("pa",  "ぱぴぷぺぽ",      ["pa", "pi", "pu", "pe", "po"]),
    ("small", "ぁぃぅぇぉゃゅょっゎ",
              ["xa", "xi", "xu", "xe", "xo", "xya", "xyu", "xyo", "xtsu", "xwa"]),
]


def katakana(rows):
    """The same table shifted by 0x60, plus ヴ and the long-vowel mark."""
    out = []
    for row, chars, rom in rows:
        out.append(("K" + row, "".join(chr(ord(c) + 0x60) for c in chars), rom))
    out.append(("Kvu", "ヴ", ["vu"]))
    out.append(("long", "ー", ["-"]))
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    glyphs = []
    for kind, rows in (("hiragana", HIRAGANA), ("katakana", katakana(HIRAGANA))):
        for row, chars, roms in rows:
            assert len(chars) == len(roms), row
            for order, (c, r) in enumerate(zip(chars, roms), 1):
                glyphs.append({"cp": f"U+{ord(c):04X}", "char": c, "romaji": r,
                               "row": row, "order": order, "kind": kind})
    book = {
        "script": "vocab",
        "name": "Kana (hiragana + katakana)",
        "count": len(glyphs),
        "traceFont": "klee-one",
        "printFont": "noto-sans-jp",
        "strokeSource": "kanjivg",
        "note": "Generated by build/kana_glyphs.py. Every hiragana and katakana, "
                "so a vocabulary deck never has to add a character.",
        "glyphs": glyphs,
    }
    out.write_text(json.dumps(book, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(glyphs)} glyphs -> {out}")


if __name__ == "__main__":
    main()
