#!/usr/bin/env python3
"""Write the kana game's glyph list and stroke book (scripts/kana/).

The kana game (v0.1.76) asks for hiragana, katakana or both. Its hiragana are
the hiragana game's 75 (the gojūon, the voiced rows, ゃゅょ and っ), with
their accents and hook notes; its katakana are the 75 that mirror them, one
block up (0x60), each wearing its twin's accent: カ says KAH like か. The
same small kana are left out of both (ァィゥェォ, ヴ, ー), for the reasons the
hiragana pack leaves them out.

Strokes: the hiragana pack's book for the hiragana, the vocab pack's for the
katakana. Same converter, same source. Nothing here is typed by hand, so the
two games' characters cannot drift from their packs.

Usage:  kana_game.py            # writes scripts/kana/glyphs.json, strokes.json
"""

import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KATA = 0x60


def main():
    hira = json.loads((ROOT / "scripts/hiragana/glyphs.json").read_text(encoding="utf-8"))
    hbook = json.loads((ROOT / "scripts/hiragana/strokes.json").read_text(encoding="utf-8"))
    vbook = json.loads((ROOT / "scripts/vocab/strokes.json").read_text(encoding="utf-8"))
    font = hbook["activeFont"]
    hl, vl = hbook["fonts"][font]["letters"], vbook["fonts"][font]["letters"]

    glyphs, letters = [], {}
    for g in hira["glyphs"]:
        g = dict(g, kind="hiragana")
        glyphs.append(g)
        letters[g["char"]] = hl[g["char"]]
    for g in hira["glyphs"]:
        c = chr(ord(g["char"]) + KATA)
        k = {"cp": f"U+{ord(c):04X}", "char": c, "romaji": g["romaji"],
             "row": "K" + g["row"], "order": g["order"], "kind": "katakana"}
        if g.get("gaijin"):
            k["gaijin"] = g["gaijin"]
        glyphs.append(k)
        if c not in vl:
            raise SystemExit(f"{c} has no strokes in the vocab book")
        letters[c] = vl[c]

    out = ROOT / "scripts/kana"
    out.mkdir(exist_ok=True)
    gl = {"script": "kana", "name": "Kana (the hiragana game's 75, and the katakana that mirror them)",
          "count": len(glyphs), "traceFont": hira.get("traceFont", "klee-one"),
          "printFont": hira.get("printFont", "noto-sans-jp"), "strokeSource": "kanjivg",
          "note": "Generated by build/kana_game.py from scripts/hiragana and scripts/vocab. Do not edit.",
          "glyphs": glyphs}
    book = copy.deepcopy({k: v for k, v in hbook.items() if k != "fonts"})
    book["note"] = "Generated by build/kana_game.py: the hiragana pack's strokes and the vocab pack's katakana. " + hbook.get("note", "")
    book["fonts"] = {font: {"letters": letters}}
    (out / "glyphs.json").write_text(json.dumps(gl, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "strokes.json").write_text(json.dumps(book, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"{len(glyphs)} glyphs -> {out}")


if __name__ == "__main__":
    main()
